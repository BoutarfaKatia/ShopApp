#!/bin/bash
set -e
mysql -u root -p"$MYSQL_ROOT_PASSWORD" <<EOSQL
CREATE DATABASE IF NOT EXISTS auth_db    CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS product_db CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS order_db   CHARACTER SET utf8mb4;

CREATE USER IF NOT EXISTS 'auth_user'@'%'    IDENTIFIED BY '${AUTH_DB_PASSWORD}';
CREATE USER IF NOT EXISTS 'product_user'@'%' IDENTIFIED BY '${PRODUCT_DB_PASSWORD}';
CREATE USER IF NOT EXISTS 'order_user'@'%'   IDENTIFIED BY '${ORDER_DB_PASSWORD}';

GRANT ALL PRIVILEGES ON auth_db.*    TO 'auth_user'@'%';
GRANT ALL PRIVILEGES ON product_db.* TO 'product_user'@'%';
GRANT ALL PRIVILEGES ON order_db.*   TO 'order_user'@'%';
FLUSH PRIVILEGES;
EOSQL